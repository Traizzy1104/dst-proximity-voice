Brings true distance-based directional 3D voice chat to Don't Starve Together. Talk to your friends around the campfire, hear them getting quieter as they wander off into the dark, and hear which direction danger is coming from.

Features:
- Dynamic 3D Positional Audio: Volume and stereo panning (left/right) adjust based on player distance.
- Cave Isolation: Players in caves and on the surface cannot hear each other.
- Client-Side Mod: Works on ANY server you join! The server does not need this mod.
- Optimized: Only updates coordinates when moving to keep log files minimal.

Quick Setup Guide:
This mod uses the standard Mumble Link protocol.
1. Subscribe to this mod and enable it in DST under Mods -> Client Mods.
2. Install Mumble and connect to your group's voice server.
3. Download the Companion Launcher from GitHub:
https://github.com/Traizzy1104/dst-proximity-voice/releases

The Launcher auto-detects your game, configures Mumble's 3D settings with 1 click, and starts the voice bridge.

Open Source & Setup Guide:
